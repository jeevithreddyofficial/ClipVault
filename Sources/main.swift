// ClipVault — a tiny clipboard history for the macOS menu bar.
import AppKit

@MainActor
final class ClipVault: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private let maxItems = 15
    private let previewLength = 60

    private var statusItem: NSStatusItem!
    private var history: [String] = []
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Pasteboard types that password managers use to mark secrets — never stored.
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func applicationDidFinishLaunching(_ notification: Notification) {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        if let button = statusItem.button {
            let image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "ClipVault")
            image?.isTemplate = true
            button.image = image
            button.toolTip = "ClipVault"
        }

        let menu = NSMenu()
        menu.delegate = self
        menu.autoenablesItems = false
        statusItem.menu = menu

        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.pollPasteboard() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: - Clipboard monitoring

    private func pollPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        if let types = pb.types, !ignoredTypes.isDisjoint(with: types) { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        add(text)
    }

    private func add(_ text: String) {
        history.removeAll { $0 == text }
        history.insert(text, at: 0)
        if history.count > maxItems { history.removeLast(history.count - maxItems) }
    }

    // MARK: - Menu

    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()

        if history.isEmpty {
            let empty = NSMenuItem(title: "No clipboard history yet", action: nil, keyEquivalent: "")
            empty.isEnabled = false
            menu.addItem(empty)
        } else {
            for (index, text) in history.enumerated() {
                let item = NSMenuItem(title: preview(text), action: #selector(copyItem(_:)), keyEquivalent: "")
                item.target = self
                item.tag = index
                item.toolTip = text.count > 500 ? String(text.prefix(500)) + "…" : text
                if index < 9 { item.keyEquivalent = String(index + 1); item.keyEquivalentModifierMask = [] }
                menu.addItem(item)
            }
        }

        menu.addItem(.separator())

        let clear = NSMenuItem(title: "Clear History", action: #selector(clearHistory), keyEquivalent: "")
        clear.target = self
        clear.isEnabled = !history.isEmpty
        menu.addItem(clear)

        let quit = NSMenuItem(title: "Quit ClipVault", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        menu.addItem(quit)
    }

    private func preview(_ text: String) -> String {
        let oneLine = text
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            .joined(separator: " ⏎ ")
        return oneLine.count > previewLength ? String(oneLine.prefix(previewLength)) + "…" : oneLine
    }

    @objc private func copyItem(_ sender: NSMenuItem) {
        guard history.indices.contains(sender.tag) else { return }
        let text = history[sender.tag]
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount   // don't re-capture our own write
        add(text)                           // move it to the top
    }

    @objc private func clearHistory() {
        history.removeAll()
    }
}

MainActor.assumeIsolated {
    let app = NSApplication.shared
    let delegate = ClipVault()
    app.delegate = delegate
    app.setActivationPolicy(.accessory)
    app.run()
}
